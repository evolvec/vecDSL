#!/usr/bin/env python3
"""spec/GRAMMAR.md: the vecDSL 1.0 grammar rule by rule in EBNF, with the concept comment of each rule and the design
decisions (D1 to D15, Rv) its comments cite.

The EBNF is printed from the parse trees of org.ftn.vecDSL/tools/grammar_report.py, so the document follows the .xtext:
`'kw'` is a keyword, `feature=X` an assignment, `feature+=X` a list element, `feature?=X` a flag, `[T]` a cross-reference
to an element of type T written by its name, `{T}` the creation of a T, and `?`, `*`, `+` the usual repetitions.
Section headings are those of the grammar ("1. PROGRAM", ...).

Usage: grammar_doc.py [--grammar FILE] [--out FILE]
"""

import argparse
import re
import sys
from pathlib import Path

WORKSPACE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(WORKSPACE / "org.ftn.vecDSL/tools"))
import grammar_report  # noqa: E402

RULE = re.compile(r"^(?:(fragment|enum|terminal)\s+)?([A-Z]\w*)(\*)?(?:\s+returns\s+(\S+))?\s*:\s*$")
SECTION = re.compile(r"^// (\d+(?:\.\d+)?\.? .+?)\s*-*$")
DECISION = re.compile(r"\b(D\d{1,2}|Rv)\b")


def ebnf(tree, top=True):
    tag = tree[0]
    if tag == "seq":
        return " ".join(ebnf(item, False) for item in tree[1])
    if tag == "alt":
        text = " | ".join(ebnf(branch, False) for branch in tree[1])
        return text if top else f"( {text} )"
    if tag in ("opt", "star", "plus"):
        inner = ebnf(tree[1], False)
        if tree[1][0] in ("seq",) and len(tree[1][1]) > 1:
            inner = f"( {inner} )"
        return inner + {"opt": "?", "star": "*", "plus": "+"}[tag]
    if tag == "kw":
        return f"'{tree[1]}'"
    if tag == "call":
        return tree[1]
    if tag == "xref":
        return f"[{tree[1]}]"
    if tag == "action":
        return "{" + tree[1].replace(" . ", ".").replace(" = ", "=") + "}"
    if tag == "assign":
        return f"{tree[1]}{tree[2]}{ebnf(tree[3], False)}"
    raise ValueError(tree)


def comments(text):
    """Rule name -> (section, concept comment, decisions cited in the rule's comments)."""
    result, section, block, current = {}, "", [], None
    for raw in text.splitlines():
        line = raw.strip()
        sub = re.match(r"^// --- (\d+\.\d+ .+?) -+$", line)
        if sub and current is None:
            section, block = sub.group(1), []
            continue
        if line.startswith("// ===") or line.startswith("// ---"):
            continue
        match = SECTION.match(line)
        if match and current is None and re.match(r"^\d+\.\s+[A-Z]{2}", match.group(1)):
            section, block = match.group(1).rstrip(" -"), []
            continue
        rule = RULE.match(line)
        if rule and current is None:
            current = rule.group(2)
            result[current] = [section, " ".join(block), set(DECISION.findall(" ".join(block)))]
            block = []
            continue
        if current is not None:
            if line == ";" or line.endswith(";") and not line.startswith("//"):
                current = None
                continue
            if "//" in line:
                result[current][2] |= set(DECISION.findall(line[line.index("//"):]))
            continue
        if line.startswith("//"):
            block.append(line[2:].strip())
        elif line:
            block = []
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--grammar", type=Path, default=WORKSPACE / "spec/VecDSL-1.0.xtext")
    parser.add_argument("--out", type=Path, default=WORKSPACE / "spec/GRAMMAR.md")
    args = parser.parse_args()
    text = args.grammar.read_text(encoding="utf-8")
    rules = grammar_report.load(args.grammar)
    docs = comments(text)
    order = [m.group(2) for m in (RULE.match(l.strip()) for l in text.splitlines()) if m]
    out = ["# vecDSL 1.0 grammar", "",
           f"Generated by `spec/tools/grammar_doc.py` from `{args.grammar.name}` (grammar 7.1 frozen as vecDSL 1.0). Do not "
           "edit by hand; the grammar file is the source. Notation: `'kw'` keyword, `f=X` assignment, `f+=X` list "
           "element, `f?=X` flag, `[T]` reference to a T by name, `{T}` creation of a T, `?` `*` `+` repetition. "
           "Decisions are those the rule's comments cite (D1 to D15 of the grammar header and the REMOVED IN V7 "
           "block; Rv is an accepted finding of the v7 review).", ""]
    kinds = {k: sum(1 for r in rules.values() if r["kind"] == k) for k in ("parser", "fragment", "datatype", "enum",
                                                                            "terminal")}
    out += [f"Rules: {kinds['parser']} parser rules, {kinds['fragment']} fragments, {kinds['datatype']} datatype rules, "
            f"{kinds['enum']} enumerations, {kinds['terminal']} terminal rule (plus the Xtext common terminals).", ""]
    cited = {}
    section = None
    for name in order:
        rule = rules.get(name)
        if rule is None:
            continue
        sec, concept, decisions = docs.get(name, ["", "", set()])
        if sec != section and sec:
            out += [f"## {sec}", ""]
            section = sec
        for decision in decisions:
            cited.setdefault(decision, []).append(name)
        kind = {"parser": "", "fragment": "fragment ", "datatype": "datatype ", "enum": "enum ",
                "terminal": "terminal "}[rule["kind"]]
        out.append(f"### {kind}{name}" + (f" (returns {rule['returns']})" if rule["returns"] else ""))
        out.append("")
        if concept:
            out += [concept, ""]
        out.append("Decisions: " + (", ".join(sorted(decisions, key=decision_key)) if decisions else "none cited") + ".")
        out.append("")
        if rule["kind"] == "enum":
            body = " | ".join(f"{lit}='{kw}'" for lit, kw in zip(rule["literals"], rule["keywords"]))
        elif rule["kind"] == "terminal":
            body = " ".join(rule["body"].split())
        else:
            body = ebnf(rule["tree"])
        out += ["```", f"{name} ::= {body}", "```", ""]
    out += ["## Decisions and the rules that cite them", "", "| decision | rules |", "|---|---|"]
    out += [f"| {d} | {', '.join(cited[d])} |" for d in sorted(cited, key=decision_key)]
    elsewhere = sorted(set(DECISION.findall(text)) - set(cited), key=decision_key)
    if elsewhere:
        out += ["", f"Cited only in section headings, the file header or the REMOVED IN V7 block: {', '.join(elsewhere)}."]
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{args.out}: {len(order)} rules, {len(cited)} decisions cited")


def decision_key(decision):
    return (1, 0) if decision == "Rv" else (0, int(decision[1:]))


if __name__ == "__main__":
    main()
