#!/usr/bin/env python3
"""spec/METAMODEL.md: every EClass of model/generated/VecDSL.ecore with its features, and the derivation of the 456 rows
of the COVERAGE.md matrices.

Groups: Method, Concept, AlterOperation and ExtensionItem classes (the four row kinds of COVERAGE.md), then the remaining
classes (query helpers, filters, literals, extension members), each with its supertypes and every feature: name,
kind (attribute, containment, reference), type and multiplicity. Inherited features are listed under the class that
declares them; a leaf class's full feature list is the union along its supertypes (EMF's eAllStructuralFeatures).

Usage: metamodel_doc.py [--workspace DIR] [--coverage FILE] [--out FILE]
  --coverage  a COVERAGE.md whose construct column the derivation is checked against
              (default: the milvus matrix)
"""

import argparse
import re
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

WORKSPACE = Path(__file__).resolve().parents[2]
XSI_TYPE = "{http://www.w3.org/2001/XMLSchema-instance}type"
ROOTS = ["Method", "Concept", "AlterOperation", "ExtensionItem"]


def load(path):
    classes, enums = {}, {}
    for classifier in ElementTree.parse(path).getroot().findall("eClassifiers"):
        name = classifier.get("name")
        if classifier.get(XSI_TYPE) == "ecore:EEnum":
            enums[name] = [literal.get("literal") or literal.get("name") for literal in classifier.findall("eLiterals")]
            continue
        supers = [ref.split("//")[-1] for ref in classifier.get("eSuperTypes", "").split()]
        features = []
        for feature in classifier.findall("eStructuralFeatures"):
            kind = feature.get(XSI_TYPE).split(":")[-1]
            if kind == "EReference":
                kind = "containment" if feature.get("containment") == "true" else "reference"
            else:
                kind = "attribute"
            features.append((feature.get("name"), kind, feature.get("eType", "").split("//")[-1],
                             "0..*" if feature.get("upperBound") == "-1" else "0..1"))
        classes[name] = {"supers": supers, "features": features}
    return classes, enums


def ancestors(classes, name):
    result, todo = [], [name]
    while todo:
        for parent in classes[todo.pop(0)]["supers"]:
            if parent not in result:
                result.append(parent)
                todo.append(parent)
    return result


def all_features(classes, name):
    result, seen = [], set()

    def visit(cls):
        for parent in classes[cls]["supers"]:
            visit(parent)
        for feature in classes[cls]["features"]:
            if feature[0] not in seen:
                seen.add(feature[0])
                result.append(feature)

    visit(name)
    return result


def leaves(classes, root):
    """Classes under root that no other class under root extends (the row classes of COVERAGE.md)."""
    members = [name for name in classes if root in ancestors(classes, name)]
    extended = {parent for name in members for parent in classes[name]["supers"]}
    return sorted(name for name in members if name not in extended)


def coverage_constructs(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith("| construct |"))
    result = []
    for line in lines[start + 2:]:
        if not line.startswith("|"):
            break
        result.append(re.split(r"(?<!\\)\|", line.strip()[1:-1])[0].strip())
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--workspace", type=Path, default=WORKSPACE)
    parser.add_argument("--coverage", type=Path,
                        default=WORKSPACE / "org.ftn.vecDSL/src/org/ftn/vecDSL/generator/milvus/COVERAGE.md")
    parser.add_argument("--out", type=Path, default=WORKSPACE / "spec/METAMODEL.md")
    args = parser.parse_args()
    classes, enums = load(args.workspace / "org.ftn.vecDSL/model/generated/VecDSL.ecore")
    rows = {root: leaves(classes, root) for root in ROOTS}
    method_features = [(m, f[0]) for m in rows["Method"] for f in all_features(classes, m)]
    derived = [f"{root} {name}" for root in ROOTS for name in rows[root]] + [f"{m}.{f}" for m, f in method_features]
    actual = coverage_constructs(args.coverage)
    missing, extra = sorted(set(derived) - set(actual)), sorted(set(actual) - set(derived))
    grouped = {name for root in ROOTS for name in rows[root]} | set(ROOTS)
    intermediate = sorted(name for root in ROOTS for name in classes
                          if root in ancestors(classes, name) and name not in rows[root])
    out = ["# vecDSL 1.0 metamodel inventory", "",
           "Generated by `spec/tools/metamodel_doc.py` from `org.ftn.vecDSL/model/generated/VecDSL.ecore` (the metamodel "
           "Xtext infers from VecDSL.xtext 7.1, namespace `http://www.ftn.org/vecDSL/VecDSL/7`). Do not edit by hand.", "",
           f"Classes: {len(classes)}; enumerations: {len(enums)} with {sum(len(v) for v in enums.values())} literals. No "
           "class is abstract in the Ecore model; a supertype that no rule instantiates is marked \"supertype\".", "",
           "## Derivation of the COVERAGE.md rows", "",
           "Every COVERAGE.md has one row per leaf class of the four row kinds and one row per structural feature of each "
           "leaf Method class, inherited features included:", "",
           "| part | count |", "|---|---|"]
    for root in ROOTS:
        out.append(f"| leaf {root} classes | {len(rows[root])} |")
    out += [f"| features of the leaf Method classes | {len(method_features)} |",
            f"| **rows** | **{len(derived)}** |", "",
            f"Intermediate supertypes, which have no row of their own: {', '.join(intermediate)}.", "",
            f"Check against the {args.coverage.parent.name} `{args.coverage.name}`: {len(actual)} rows; "
            + ("the derived construct set equals the matrix's." if not missing and not extra else
               f"derived but absent: {missing}; present but not derived: {extra}.")]
    out += ["", "## Classes by row kind", ""]
    for root in ROOTS:
        out += [f"### {root} ({len(rows[root])} leaf classes)", ""]
        for name in [root] + intermediate_of(classes, root, rows[root]) + rows[root]:
            out += render(classes, name, supertype=name not in rows[root])
    out += ["## Other classes", ""]
    for name in sorted(n for n in classes if n not in grouped and n not in intermediate):
        out += render(classes, name, supertype=any(name in classes[c]["supers"] for c in classes))
    out += ["## Enumerations", "", "| enumeration | literals |", "|---|---|"]
    out += [f"| {name} | {' '.join(literals)} |" for name, literals in sorted(enums.items())]
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{args.out}: {len(derived)} derived rows; matrix {len(actual)}; missing {len(missing)}, extra {len(extra)}")
    return 0 if not missing and not extra else 1


def intermediate_of(classes, root, leaf_names):
    return sorted(name for name in classes if root in ancestors(classes, name) and name not in leaf_names)


def render(classes, name, supertype):
    info = classes[name]
    header = f"#### {name}" + (" (supertype)" if supertype else "")
    lines = [header, "", f"Supertypes: {', '.join(info['supers']) or 'none'}.", ""]
    if info["features"]:
        lines += ["| feature | kind | type | multiplicity |", "|---|---|---|---|"]
        lines += [f"| {f[0]} | {f[1]} | {f[2]} | {f[3]} |" for f in info["features"]]
    else:
        lines.append("No features of its own.")
    return lines + [""]


if __name__ == "__main__":
    sys.exit(main())
