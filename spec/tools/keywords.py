#!/usr/bin/env python3
"""Reserved words of vecDSL (spec/KEYWORDS.txt) and a check of names in programs against them.

Hard keywords are the quoted words of the grammar minus the soft keywords that ValidID admits as names; the
algorithm is the generators' keyword check. A hard keyword cannot be used as a name
unless escaped with '^'. Where a name is optional (boost-fn, stage, quantization, vector-field), a hard keyword after the
introducing word is the next clause, not a name, and is not reported.

Usage: keywords.py [--grammar FILE] [--out FILE] [program.vecDSL ...]
"""

import argparse
import re
from pathlib import Path

WORKSPACE = Path(__file__).resolve().parents[2]
NAMED = ("collection|field|vector-field|analyzer|vector-index|payload-index|tenant|namespace|function|embedding-model|"
         "reranker|alias|partition|field-limit|backup-schedule|filter|auth|role|metrics|connection|logical-db|cluster|"
         "file-resource|generative-model|quantization|boost-fn|stage|as")

OPTIONAL_NAME = {"boost-fn", "stage", "quantization", "vector-field"}


def keywords(grammar_text):
    grammar = re.sub(r"//[^\n]*|/\*.*?\*/", "", grammar_text, flags=re.S)
    words = set(re.findall(r"'([A-Za-z][A-Za-z0-9_-]*)'", grammar))
    valid = re.search(r"ValidID returns ecore::EString:(.*?);", grammar, re.S).group(1)
    soft = set(re.findall(r"'([^']+)'", valid))
    return sorted(words - soft), sorted(soft)


def conflicts(hard, program):
    text = re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/', lambda m: m.group(0) if m.group(0).startswith('"') else "",
                  program.read_text(encoding="utf-8"), flags=re.S)
    names = re.findall(r"(?m)^\s*\"?([A-Za-z_][A-Za-z0-9_]*):\s", text)
    for owner, name in re.findall(r"(?<![-\w])(" + NAMED + r")\s+([A-Za-z_][A-Za-z0-9_]*)", text):
        if not (owner in OPTIONAL_NAME and name in hard):
            names.append(name)
    return sorted(name for name in set(names) if name in hard)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--grammar", type=Path, default=WORKSPACE / "spec/VecDSL-1.0.xtext")
    parser.add_argument("--out", type=Path)
    parser.add_argument("programs", nargs="*", type=Path)
    args = parser.parse_args()
    hard, soft = keywords(args.grammar.read_text(encoding="utf-8"))
    if args.out:
        lines = ["# vecDSL 1.0 reserved words, generated by spec/tools/keywords.py from " + args.grammar.name,
                 f"# {len(hard)} hard keywords (frozen for 1.0; a name equal to one must be written with a leading '^').",
                 f"# Soft keywords usable as names (ValidID, D7): {' '.join(soft)}"]
        args.out.write_text("\n".join(lines + hard) + "\n", encoding="utf-8", newline="\n")
    bad = 0
    for program in args.programs:
        for name in conflicts(set(hard), program):
            print(f"{program}: '{name}' is a hard keyword")
            bad += 1
    print(f"{len(hard)} hard keywords, {len(soft)} soft keywords; {bad} conflicts")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
