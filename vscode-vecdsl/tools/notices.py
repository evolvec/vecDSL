def bundled():
    text = (ROOT / "out" / "extension.js").read_text("utf-8")
    names = sorted({match.group(1) for match in re.finditer(r"^// node_modules/((?:@[^/]+/)?[^/]+)/", text, re.M)})
    packages = []
    for name in names:
        folder = ROOT / "node_modules" / name
        manifest = json.loads((folder / "package.json").read_text("utf-8"))
        license_file = next(path for path in sorted(folder.iterdir()) if path.name.lower().startswith("licen"))
        packages.append((manifest["name"], manifest["version"], manifest["license"], license_file))
    return packages


def notices():
    packages = bundled()
    lines = ["Third-party notices for vscode-vecdsl", "",
             "The vsix contains out/extension.js, which bundles the npm packages of part 1, and server/vecdsl-lsp.jar,",
             "the vecDSL Language Server with the components of part 2. Generated by tools/notices.py.", "",
             "Part 1: npm packages in out/extension.js", ""]
    for name, version, spdx, _ in packages:
        lines.append("- %s %s: %s" % (name, version, spdx))
    lines += ["", "Part 2: components of server/vecdsl-lsp.jar", ""]
    for component, version, packages_in_jar, spdx, source, _ in SERVER:
        lines += ["- %s" % component, "  version: %s" % version, "  classes: %s" % packages_in_jar,
                  "  license: %s" % spdx, "  read from: %s" % source]
    lines += ["", "License texts", ""]
    for name, version, _, license_file in packages:
        lines += ["=" * 100, "%s %s (%s)" % (name, version, license_file.name), "=" * 100,
                  license_file.read_text("utf-8").rstrip(), ""]
    for text in sorted({entry[5] for entry in SERVER if entry[5]} - {"EPL-2.0, Apache-2.0"}):
        users = ", ".join(entry[0].split(":")[0] for entry in SERVER if entry[5] and text in entry[5].split(", "))
        lines += ["=" * 100, "%s (%s)" % (text, users), "=" * 100,
                  (LICENSES / (text + ".txt")).read_text("utf-8").rstrip(), ""]
    return "\n".join(lines) + "\n"


def main():
    text = notices()
    if "--check" in sys.argv[1:]:
        same = NOTICES.exists() and NOTICES.read_text("utf-8") == text
        print("notices: %s" % ("up to date" if same else "differ from tools/notices.py, run it"))
        return 0 if same else 1
    NOTICES.write_text(text, "utf-8", newline="\n")
    print("wrote: %s (%d npm packages, %d server components)" % (NOTICES.name, len(bundled()), len(SERVER)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
